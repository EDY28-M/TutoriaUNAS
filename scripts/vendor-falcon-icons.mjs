import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const origin = 'https://raw.githubusercontent.com/FortAwesome/Font-Awesome/6.5.1';
const response = await fetch(`${origin}/metadata/icons.json`);
if (!response.ok) throw new Error(`Font Awesome metadata: ${response.status}`);
const metadata = await response.json();
const source = await readFile(resolve(root, 'frontend/src/components/ui/icons.tsx'), 'utf8');
const selected = {};
for (const match of source.matchAll(/crearIcono\('([^']+)'(?:, '(solid|regular)')?\)/g)) {
  const [, name, style = 'solid'] = match;
  const glyph = metadata[name]?.svg?.[style];
  if (!glyph || !metadata[name].free.includes(style)) throw new Error(`Missing free icon: ${style}:${name}`);
  selected[`${style}:${name}`] = { width: glyph.width, height: glyph.height, path: glyph.path };
}
const target = resolve(root, 'frontend/src/assets/vendor/fontawesome-icons.ts');
await writeFile(target, `/** Font Awesome Free 6.5.1 — official SVG paths, CC BY 4.0.\n * Source: ${origin}/metadata/icons.json\n * Generated by scripts/vendor-falcon-icons.mjs. See LICENSE-FONT-AWESOME.txt.\n */\nexport const fontAwesomeIcons: Record<string, { width: number; height: number; path: string }> = ${JSON.stringify(selected, null, 2)};\n`);
const license = await fetch(`${origin}/LICENSE.txt`);
if (!license.ok) throw new Error(`Font Awesome license: ${license.status}`);
await writeFile(resolve(root, 'frontend/src/assets/vendor/LICENSE-FONT-AWESOME.txt'), await license.text());
console.log(`Vendored ${Object.keys(selected).length} official SVG icons from Font Awesome Free 6.5.1.`);
